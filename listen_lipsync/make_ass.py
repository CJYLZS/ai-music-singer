#!/usr/bin/env python3
"""增强 LRC → 双行滚动的 KTV 字幕（ASS 字幕文件）。

画面上永远是两行：上面是**正在唱**的那句（逐字扇光，唱过的字变色），
下面是**下一句**的预览（暗色）。唱完一句就整体上滚。

为什么用 ASS 烧字而不是在 a25rig 里画：libass 原生支持 `\\kf` 扇光，改字幕不用重渲
整片（几秒重烧 vs 两分钟重渲），且排版能力（描边/阴影/淡入/对齐）现成。

字级时间从哪来：
  * 缓存是逐字增强 LRC（酷狗 KRC）→ 直接用
  * 只有行级 → 按字数把行时长均分（`--even`），或先跑 make_cues.py --text 拿真字级

用法:
    python listen_lipsync/make_ass.py data/songs/云烟成雨.lrc -o out.ass \\
        --size 1920x1080 --start 0 --end 100
    # 烧进视频
    FONTCONFIG_FILE=... ffmpeg -i mv.mp4 -vf "ass=out.ass" -c:a copy out.mp4
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from get_lyrics import read_enhanced  # noqa: E402


def ass_ts(t):
    """ASS 时间戳 h:mm:ss.cc（百分秒，只有两位）。"""
    t = max(0.0, t)
    h = int(t // 3600)
    m = int(t % 3600 // 60)
    s = t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def ass_color(hexstr, alpha=0):
    """#RRGGBB → ASS 的 &HAABBGGRR（注意 ASS 是 BGR 且 alpha 反向）。"""
    h = hexstr.lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return f"&H{alpha:02X}{b:02X}{g:02X}{r:02X}"


def infer_char_times(line, even=False):
    """返回 [(时长秒, 字)]。逐字数据直接用；行级则均分。"""
    if line.get("chars") and not even:
        return [(dur, ch) for _t, dur, ch in line["chars"]]
    txt = line["text"]
    span = (line.get("end") or line["start"] + 3.0) - line["start"]
    n = max(1, len(txt))
    return [(span / n, ch) for ch in txt]


def build_lines(lrc_lines, min_gap=0.05, default_dur=3.0, max_hold=1.2):
    """补齐每行的 end，并按行内长静音拆行。

    行级 LRC 常把间奏吞进行内（末字被拉到下一句开头），逐字 KRC 没这问题。
    这里统一兜一手：行时长明显超过字级时间之和时，只保留字级覆盖的部分。
    """
    out = []
    for i, ln in enumerate(lrc_lines):
        nxt = lrc_lines[i + 1]["start"] if i + 1 < len(lrc_lines) else None
        end = ln.get("end")
        if end is None:
            end = (nxt - min_gap) if nxt else ln["start"] + default_dur
        if nxt:
            end = min(end, nxt - min_gap)
        end = max(end, ln["start"] + 0.3)
        if not ln["text"].strip():
            continue
        out.append({"start": ln["start"], "end": end, "text": ln["text"],
                    "chars": ln.get("chars")})
    # 行尾拖尾裁剪：字级时间之和远小于行跨度时，说明尾部是静音
    for ln in out:
        if ln.get("chars"):
            covered = ln["chars"][-1][0] + ln["chars"][-1][1]
            if ln["end"] - covered > max_hold:
                ln["end"] = covered + max_hold
    return out


def karaoke_text(line, even=False, tag="kf"):
    """生成 {\\kf<厘秒>}字 序列。厘秒取整不能为 0，否则那个字会瞬闪。"""
    parts = []
    for dur, ch in infer_char_times(line, even):
        cs = max(1, int(round(dur * 100)))
        parts.append(f"{{\\{tag}{cs}}}{ch}")
    return "".join(parts)


HEADER = """\
[Script Info]
Title: KTV lyrics (generated by make_ass.py)
ScriptType: v4.00+
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {w}
PlayResY: {h}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Cur,{font},{fs},{sung},{pending},{outline},{back},{bold},0,0,0,100,100,0,0,1,{ow},{sh},{align},{ml},{mr},{mv},1
Style: Nxt,{font},{fs2},{dim},{dim},{outline},{back},0,0,0,0,100,100,0,0,1,{ow2},{sh},{align},{ml},{mr},{mv2},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


def render(lines, args):
    w, h = args.size
    # ASS alignment: 7=左上 8=中上 9=右上 / 1=左下 2=中下 3=右下
    align = {"tl": 7, "tc": 8, "tr": 9, "bl": 1, "bc": 2, "br": 3}[args.pos]
    bottom = align <= 3
    fs = args.font_size
    fs2 = int(round(fs * args.next_scale))
    gap = int(round(fs * args.line_gap))
    # 当前行永远在上、预览行在下。MarginV 顶部对齐时从顶边量、底部对齐时从底边量，
    # 所以底部对齐要反过来：**主行**拿更大的 MarginV 才会被顶到上面去。
    if bottom:
        mv, mv2 = args.margin_y + fs2 + gap, args.margin_y
    else:
        mv, mv2 = args.margin_y, args.margin_y + fs + gap
    # 两行都半透明，减少对角色的遮挡。ASS 的 alpha 是反的：00=不透明、FF=全透。
    a1 = args.alpha                       # 当前行
    a2 = min(255, args.alpha + args.next_alpha)  # 预览行再淡一档
    head = HEADER.format(
        w=w, h=h, font=args.font, fs=fs, fs2=fs2,
        sung=ass_color(args.color_sung, a1),
        pending=ass_color(args.color_pending, a1),
        dim=ass_color(args.color_next, a2),
        outline=ass_color(args.color_outline, a1),
        back=ass_color("#000000", min(255, a1 + 0x40)),
        bold=-1 if args.bold else 0,
        ow=args.outline, ow2=max(1, args.outline - 1), sh=args.shadow,
        align=align, ml=args.margin_x, mr=args.margin_x,
        mv=mv, mv2=mv2,
    )
    ev = []
    t0, t1 = args.start, args.end
    fade = f"{{\\fad({args.fade},{args.fade})}}" if args.fade else ""

    slots = no_overlap(lines, args.lead, args.hold)

    for i, ln in enumerate(lines):
        nxt = lines[i + 1] if i + 1 < len(lines) else None
        # 上行槽的占用区间（已保证与相邻行不重叠）
        show, end = slots[i]
        if end <= t0 or show >= t1:
            continue
        show, end = max(show, t0), min(end, t1)
        if end - show < 0.05:
            continue
        # \k 从事件起点开始计时，所以要先用一个静默 \k 吃掉 lead
        pre = int(round((ln["start"] - show) * 100))
        body = (f"{{\\k{pre}}}" if pre > 0 else "") + karaoke_text(ln, args.even)
        ev.append(f"Dialogue: 1,{ass_ts(show - t0)},{ass_ts(end - t0)},Cur,,0,0,0,,"
                  f"{fade}{body}")
        # 下一行预览：与当前行同期显示，且在下一行升到上行槽的那一刻收掉
        if nxt and args.preview:
            pv_show = show
            pv_end = min(end, slots[i + 1][0], t1)
            if pv_end - pv_show >= 0.05:
                ev.append(f"Dialogue: 0,{ass_ts(pv_show - t0)},{ass_ts(pv_end - t0)},"
                          f"Nxt,,0,0,0,,{fade}{nxt['text']}")
    return head + "\n".join(ev) + "\n"


def no_overlap(lines, lead, hold):
    """算出每行在**上行槽**的占用区间，并消除相邻行的重叠。

    两个同样式(同 margin)的事件时间重叠时，libass 会启用防碰撞、把后者下移一行 ——
    看起来就是「该滚动的时候上面空了、字留在预览槽里」。所以宁可裁 lead/hold，
    也不能让 Cur 事件互相重叠。
    """
    slots = []
    for i, ln in enumerate(lines):
        show = ln["start"] - lead
        end = ln["end"] + hold
        slots.append([show, end])
    for i in range(len(slots) - 1):
        if slots[i][1] > slots[i + 1][0]:
            # 在两行之间取中点切开，各让一半
            mid = (lines[i]["end"] + lines[i + 1]["start"]) / 2.0
            mid = min(max(mid, lines[i]["end"]), lines[i + 1]["start"])
            slots[i][1] = mid
            slots[i + 1][0] = mid
    return slots


def main():
    ap = argparse.ArgumentParser(description="增强 LRC → 双行滚动 KTV ASS 字幕",
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__)
    ap.add_argument("lrc", help="增强 LRC（get_lyrics.py 的产物）")
    ap.add_argument("-o", "--out", required=True, help="输出 .ass")
    ap.add_argument("--size", default="1920x1080", help="视频尺寸 WxH")
    ap.add_argument("--start", type=float, default=0.0, help="窗口起点秒（与视频对齐）")
    ap.add_argument("--end", type=float, default=1e9, help="窗口终点秒")
    ap.add_argument("--pos", default="tr", choices=["tr", "tl", "tc", "bl", "bc", "br"], help="位置")
    ap.add_argument("--font", default="SimHei", help="字体名（须 fontconfig 可见）")
    ap.add_argument("--font-size", type=int, default=54)
    ap.add_argument("--next-scale", type=float, default=0.72, help="预览行字号比例")
    ap.add_argument("--alpha", type=lambda s: int(s, 0), default=0x40,
                    help="两行的整体透明度 0..255（0=不透明，越大越透，默认 0x40）")
    ap.add_argument("--next-alpha", type=lambda s: int(s, 0), default=0x40,
                    help="预览行在 --alpha 之上再淡多少（默认 0x40）")
    ap.add_argument("--line-gap", type=float, default=0.35, help="行距（字号倍数）")
    ap.add_argument("--margin-x", type=int, default=48)
    ap.add_argument("--margin-y", type=int, default=40)
    ap.add_argument("--color-sung", default="#3BC8FF", help="已唱（扇光）色")
    ap.add_argument("--color-pending", default="#FFFFFF", help="未唱色")
    ap.add_argument("--color-next", default="#FFFFFF", help="预览行色")
    ap.add_argument("--color-outline", default="#101820", help="描边色")
    ap.add_argument("--outline", type=int, default=3)
    ap.add_argument("--shadow", type=int, default=1)
    ap.add_argument("--bold", action="store_true", default=True)
    ap.add_argument("--no-bold", dest="bold", action="store_false")
    ap.add_argument("--lead", type=float, default=1.0, help="提前多少秒亮出当前行")
    ap.add_argument("--hold", type=float, default=0.4, help="唱完后多停留几秒")
    ap.add_argument("--fade", type=int, default=150, help="淡入淡出毫秒，0 关闭")
    ap.add_argument("--no-preview", dest="preview", action="store_false",
                    default=True, help="只显示当前行")
    ap.add_argument("--even", action="store_true",
                    help="忽略字级时间，按字数均分（行级 LRC 用）")
    args = ap.parse_args()

    m = re.match(r"^(\d+)x(\d+)$", args.size)
    if not m:
        sys.exit(f"--size 需为 WxH，得到 {args.size!r}")
    args.size = (int(m.group(1)), int(m.group(2)))

    raw, hdr = read_enhanced(args.lrc)
    if not raw:
        sys.exit(f"{args.lrc} 里没有歌词行（可能是待填模板，请先填词）")
    lines = build_lines(raw)
    kind = "逐字" if any(l.get("chars") for l in lines) and not args.even else "行级均分"
    win = [l for l in lines if l["end"] > args.start and l["start"] < args.end]
    txt = render(lines, args)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(txt)
    nev = txt.count("Dialogue:")
    print(f"{args.lrc} → {args.out}")
    print(f"  源: {hdr.get('source', '?')}   时间: {kind}")
    print(f"  全曲 {len(lines)} 行；窗口 [{args.start:g}, {min(args.end, 1e6):g}]s 内 "
          f"{len(win)} 行 → {nev} 个字幕事件")
    print(f"  样式: {args.font} {args.font_size}px @{args.pos}"
          f"{'  + 下一行预览' if args.preview else ''}")


if __name__ == "__main__":
    main()
